/**
 * The chat persistence port — Phase D / D2.
 *
 * ## Why a port and not a dependency
 *
 * The task book (§ 七 D2) asks for a `ChatRepository` that owns the
 * persistence of chat messages. That repository lives in
 * `@kindora/storage`, which depends on `@kindora/protocol` — and
 * `@kindora/matching` must **not** depend on `@kindora/storage`:
 *
 *   - `@kindora/storage` does not depend on `@kindora/matching`, so
 *     the direction would be fine, but
 *   - adding a workspace dependency means `pnpm-lock.yaml` has to be
 *     regenerated, and CI runs `pnpm install --frozen-lockfile`. A
 *     stale lockfile fails the whole build.
 *
 * So the orchestrator talks to a **port** — a small structural
 * interface — and the desktop app adapts its `ChatRepository` to it
 * (`apps/desktop/src/lib/chat-persistence.ts`). The port is defined
 * here so that both sides agree on the shape without a package
 * dependency.
 *
 * ## The write order
 *
 * ```
 *   recordPending()  →  the message is on disk with status PENDING
 *   (the message goes out on the wire)
 *   markSent()       →  status SENT
 *        or
 *   markFailed()     →  status FAILED, with the reason
 * ```
 *
 * Writing `PENDING` **before** the send is what makes a crash honest:
 * a message that was written down and then never sent is visible as
 * `PENDING` after a restart instead of silently disappearing.
 *
 * ## What `DELIVERED` may mean
 *
 * KSA 0.1 has no delivery receipt: there is no `chat_ack` message type
 * and the peer never confirms that it read anything. So an **outbound**
 * message can never honestly reach `DELIVERED` — the port has no
 * `markDelivered` method at all, on purpose.
 *
 * A **received** message is `DELIVERED` by definition: it is on this
 * device, and its arrival is the receipt.
 *
 * See docs/修复.md § 七 D2.
 */

/**
 * Who composed a message.
 *
 * `human` — a person typed it.
 * `agent` — an agent drafted it (the human still pressed Send).
 */
export type ChatMessageSource = 'human' | 'agent';

/**
 * The delivery state of a message.
 *
 * `PENDING`   — written down, not (yet) confirmed as sent.
 * `SENT`      — handed to the transport without an error.
 * `DELIVERED` — present on the receiving device. Only ever used for
 *               inbound messages in KSA 0.1.
 * `FAILED`    — the send failed; the reason is stored with it.
 */
export type ChatMessageStatus = 'PENDING' | 'SENT' | 'DELIVERED' | 'FAILED';

/** A message that is about to go out. */
export interface PendingChatMessage {
  /** The conversation this message belongs to. */
  readonly sessionId: string;
  /** The agent id of the sender (the local agent, for outbound). */
  readonly senderAgentId: string;
  /** The message text. */
  readonly text: string;
  /** Who composed it. */
  readonly source: ChatMessageSource;
  /** The message id — generated by the orchestrator, so that the
   *  in-memory entry and the stored row share one identity. */
  readonly messageId: string;
}

/** A message the peer sent us. */
export interface ReceivedChatMessage {
  readonly sessionId: string;
  /** The agent id of the sender (the peer). */
  readonly senderAgentId: string;
  readonly text: string;
  /** Who composed it on the peer's side. */
  readonly source: ChatMessageSource;
  /** The envelope's own message id — reused verbatim, so a replayed
   *  envelope cannot produce a second row. */
  readonly messageId: string;
}

/**
 * Where the chat transcript is written.
 *
 * Every method is optional to implement? No — all four are required,
 * but the *port* itself is optional on the orchestrator: without it
 * the chat runs exactly as it did before Phase D (in memory only).
 */
export interface ChatPersistence {
  /** Write the message down **before** it is sent. */
  recordPending(message: PendingChatMessage): Promise<void>;
  /** The message went out without an error. */
  markSent(messageId: string): Promise<void>;
  /** The message could not be sent. The reason is stored with it. */
  markFailed(messageId: string, reason: string): Promise<void>;
  /** Record a message the peer sent. Its status is `DELIVERED`. */
  recordReceived(message: ReceivedChatMessage): Promise<void>;
}
